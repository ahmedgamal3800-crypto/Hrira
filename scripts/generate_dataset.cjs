// Parse CSV
const lines = rawCsv.trim().split('\n').slice(1);

const parsed = lines.map(line => {
  const match = line.match(/^(\d+),([^,]+),\"?(.*)\"?$/);
  if (!match) return null;
  const num = parseInt(match[1], 10);
  const langRaw = match[2].trim();
  let citation = match[3].trim();
  if (citation.endsWith('"')) citation = citation.slice(0, -1);
  if (citation.startsWith('"')) citation = citation.slice(1);

  return { num, langRaw, citation };
}).filter(Boolean);

console.log(`Parsed ${parsed.length} items from CSV.`);

fs.writeFileSync(path.join(__dirname, 'parsed_raw.json'), JSON.stringify(parsed, null, 2), 'utf8');
